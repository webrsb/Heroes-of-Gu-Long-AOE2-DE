def main():
    for name, status, body in BACKFILL:
        path = os.path.join(VDIR, name)
        s = io.open(path, encoding='utf-8').read()
        if '（回填 2026-08-29）' in s:
            print(f"  skip (已回填) {name}")
            continue
        lines = s.split(NL)
        # 狀態行插在標題後（第一行是 # 標題）
        if not any('**狀態**' in ln for ln in lines[:6]):
            lines.insert(1, '')
            lines.insert(2, status)
            s = NL.join(lines)
        s = s.rstrip() + NL * 2 + '---' + NL * 2 + body
        io.open(path, 'w', encoding='utf-8', newline=NL).write(s)
        print(f"  filled {name}")


